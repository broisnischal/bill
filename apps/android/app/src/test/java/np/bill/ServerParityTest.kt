package np.bill

import np.bill.core.invoice.LineInput
import np.bill.core.invoice.computeInvoice
import np.bill.core.money.amountInWords
import np.bill.core.money.formatPaisa
import np.bill.core.money.formatQuantity
import np.bill.core.nepali.BsCalendar
import np.bill.util.Iso8601
import org.junit.Assert.assertEquals
import org.junit.Test

/**
 * The device and the server have to agree, to the paisa and to the day.
 *
 * An offline bill is printed from the device's arithmetic and its calendar, and the
 * server re-checks both when the bill finally syncs; a disagreement means a bill that is
 * already in a customer's hand gets refused. These expectations were generated by running
 * the server's own `computeInvoice`, `amountInWords` and `toBsString` over the cases
 * below, so this test fails the moment the two implementations drift.
 */
class ServerParityTest {

  @Test
  fun `case 1 totals the way the server totals it`() {
    val totals = computeInvoice(
      lines = listOf(
      LineInput(description = "a", unit = "kg", quantityMilli = 2000, unitPricePaisa = 12500, discountPaisa = 0, vatApplicable = true),
      ),
      invoiceDiscountPaisa = 0,
      vatRateBp = 1300,
    )

    assertEquals(25000L, totals.subTotalPaisa)
    assertEquals(0L, totals.discountPaisa)
    assertEquals(25000L, totals.taxableAmountPaisa)
    assertEquals(0L, totals.nonTaxableAmountPaisa)
    assertEquals(3250L, totals.vatAmountPaisa)
    assertEquals(28250L, totals.totalPaisa)
    assertEquals("Rupees Two Hundred Eighty Two and Fifty Paisa Only", amountInWords(totals.totalPaisa))
  }
  @Test
  fun `case 2 totals the way the server totals it`() {
    val totals = computeInvoice(
      lines = listOf(
      LineInput(description = "a", unit = "pcs", quantityMilli = 1000, unitPricePaisa = 3333, discountPaisa = 0, vatApplicable = true),
      LineInput(description = "b", unit = "pcs", quantityMilli = 1000, unitPricePaisa = 3333, discountPaisa = 0, vatApplicable = true),
      LineInput(description = "c", unit = "pcs", quantityMilli = 1000, unitPricePaisa = 3334, discountPaisa = 0, vatApplicable = true),
      ),
      invoiceDiscountPaisa = 1000,
      vatRateBp = 1300,
    )

    assertEquals(10000L, totals.subTotalPaisa)
    assertEquals(1000L, totals.discountPaisa)
    assertEquals(9000L, totals.taxableAmountPaisa)
    assertEquals(0L, totals.nonTaxableAmountPaisa)
    assertEquals(1170L, totals.vatAmountPaisa)
    assertEquals(10170L, totals.totalPaisa)
    assertEquals("Rupees One Hundred One and Seventy Paisa Only", amountInWords(totals.totalPaisa))
  }
  @Test
  fun `case 3 totals the way the server totals it`() {
    val totals = computeInvoice(
      lines = listOf(
      LineInput(description = "a", unit = "kg", quantityMilli = 2500, unitPricePaisa = 9999, discountPaisa = 250, vatApplicable = true),
